#!/usr/bin/env python3
"""Generate ctypes declaration data from the installed C ABI (pycparser is dev-only)."""
from pathlib import Path
import argparse
import hashlib
import operator
import re
import subprocess
from pycparser import c_ast as A, c_parser

HEADERS = ('tactix.h', 'ipasir.h', 'tactix_ipasir.h')
PRELUDE = '''typedef signed char int8_t; typedef unsigned char uint8_t;
typedef short int16_t; typedef unsigned short uint16_t;
typedef int int32_t; typedef unsigned int uint32_t;
typedef long long int64_t; typedef unsigned long long uint64_t;
typedef unsigned long size_t; typedef struct FILE FILE;
#define UINT64_MAX 18446744073709551615ULL
#define UINT32_MAX 4294967295U
#define UINT64_C(x) x##ULL
#define UINT32_C(x) x##U
'''

def integer(n):
    if isinstance(n, A.Constant): return int(re.sub(r'[uUlL]+$', '', n.value), 0)
    if isinstance(n, A.Cast): return integer(n.expr)
    if isinstance(n, A.UnaryOp):
        return {'-': operator.neg, '+': operator.pos, '~': operator.invert}[n.op](integer(n.expr))
    if isinstance(n, A.BinaryOp):
        return {'+': operator.add, '-': operator.sub, '*': operator.mul,
                '/': operator.floordiv, '|': operator.or_, '&': operator.and_,
                '^': operator.xor, '<<': operator.lshift, '>>': operator.rshift}[n.op](integer(n.left), integer(n.right))
    raise ValueError('unsupported constant: ' + repr(n))

class Declarations:
    def __init__(self):
        self.records, self.aliases, self.functions = {}, {}, {}
        self.opaque, self.public_types = set(['FILE']), []

    def encode(self, n, preferred, ctype):
        if isinstance(n, A.TypeDecl): return self.encode(n.type, preferred, ctype)
        if isinstance(n, A.IdentifierType): return ' '.join(n.names)
        if isinstance(n, A.PtrDecl):
            if isinstance(n.type, A.FuncDecl): return self.encode(n.type, preferred, ctype)
            return ('*', self.encode(n.type, preferred, ctype))
        if isinstance(n, A.ArrayDecl): return ('array', self.encode(n.type, preferred, ctype), integer(n.dim))
        if isinstance(n, A.FuncDecl):
            args = [self.encode(p.type, preferred, ctype) for p in n.args.params] if n.args else []
            if args == ['void']: args = []
            return ('function', self.encode(n.type, preferred, ctype), args)
        if isinstance(n, (A.Struct, A.Union)):
            name = n.name or preferred
            if n.decls is None:
                if name not in self.records: self.opaque.add(name)
            elif name not in self.records:
                self.records[name] = None
                fields = []
                for f in n.decls:
                    assert f.name and f.bitsize is None, f
                    fields.append((f.name, self.encode(f.type, name+'__'+f.name,
                        '__typeof__((('+ctype+' *)0)->'+f.name+')')))
                self.records[name] = ('union' if isinstance(n, A.Union) else 'struct', ctype, fields)
                self.opaque.discard(name)
            return name
        raise ValueError('unsupported C declaration: ' + repr(n))

    def read(self, tree):
        for n in tree.ext:
            if isinstance(n, A.Typedef) and n.name.startswith('tactix'):
                self.public_types.append(n.name)
                code = self.encode(n.type, n.name, n.name)
                if code != n.name: self.aliases[n.name] = code
            elif isinstance(n, A.Decl) and isinstance(n.type, A.FuncDecl):
                code = self.encode(n.type, n.name, n.name)
                self.functions[n.name] = code[1:]

def generate(root, compiler):
    text, macros, hashes = PRELUDE, [], {}
    for name in HEADERS:
        p = root/'include'/name
        source = p.read_text()
        hashes[name] = hashlib.sha256(p.read_bytes()).hexdigest()
        clean = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
        for m in re.finditer(r'^#define[ \t]+(TACTIX_\w+)([^\n]*)', clean, re.M):
            tail = m[2]
            if tail.startswith('('):
                assert m[1] == 'TACTIX_LIT_INSTANCE', ('new function macro', m[1])
            elif tail.strip(): macros.append(m[1])
        text += '\n'.join(l for l in source.splitlines() if not l.startswith('#include'))+'\n'
    text += '\n'.join('const uint64_t python_constant_'+name+' = '+name+';' for name in macros)
    preprocessed = subprocess.run([compiler, '-E', '-P', '-x', 'c', '-'], input=text,
                                  text=True, capture_output=True, check=True).stdout
    tree = c_parser.CParser().parse(preprocessed)
    declarations = Declarations(); declarations.read(tree)
    constants = {n.name.removeprefix('python_constant_'): integer(n.init) for n in tree.ext
                 if isinstance(n, A.Decl) and n.name and n.name.startswith('python_constant_')}
    parts = ['# Generated by tools/api/generate_python.py; edit the public headers instead.\n']
    for name, values in [('HEADER_SHA256', hashes), ('CONSTANTS', constants),
                         ('RECORDS', declarations.records), ('ALIASES', declarations.aliases),
                         ('FUNCTIONS', declarations.functions)]:
        parts.append(name+' = {\n')
        parts.extend('    '+repr(k)+': '+repr(v)+',\n' for k,v in values.items())
        parts.append('}\n')
    parts.append('OPAQUE = '+repr(tuple(sorted(declarations.opaque)))+'\n')
    parts.append('PUBLIC_TYPES = '+repr(tuple(declarations.public_types))+'\n')
    return ''.join(parts)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument('--compiler', default='cc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = args.root/'python/tactix/_capi_schema.py'
    output = generate(args.root, args.compiler)
    if args.check:
        if target.read_text() != output: raise SystemExit('C API declarations changed: regenerate the Python schema')
    else: target.write_text(output)
